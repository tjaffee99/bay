"""Compile yards/*.json (container stacks detected on the orthophoto) into a compact TS module.
Heights are procedural (the orthophoto shows footprints, not heights): connected blocks of stacks
get a block height of 3-4 containers, a quarter of the stacks +-1 (2..5); groups of <= 3 isolated boxes are
single containers on chassis (code height 1). Colours: hue class of the stack's mean pixel colour."""
import json, sys, math, colorsys, hashlib
import numpy as np
from scipy.spatial import cKDTree
from scipy.sparse.csgraph import connected_components
from scipy.sparse import coo_matrix
B64='ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/'
def enc(v,n):
    v=int(v); out=''
    for _ in range(n): out=B64[v%64]+out; v//=64
    assert v==0, 'overflow'
    return out
def h01(*a):
    return int(hashlib.md5(repr(a).encode()).hexdigest()[:8],16)/0xffffffff
# palette index: 0 rust red, 1 maroon, 2 orange, 3 ochre, 4 green, 5 teal, 6 blue, 7 light blue, 8 grey, 9 white
def colour(rgb):
    r,g,b=[c/255 for c in rgb]
    h,s,v=colorsys.rgb_to_hsv(r,g,b)
    if s<0.18: return 9 if v>0.78 else 8
    hd=h*360
    if hd<15 or hd>=330: return 0 if v>0.55 else 1
    if hd<40: return 2
    if hd<70: return 3
    if hd<160: return 4
    if hd<195: return 5
    if hd<235: return 7 if v>0.6 and s<0.45 else 6
    if hd<290: return 6
    return 1  # magenta/pink -> maroon-red
def compile_yard(path, key):
    d=json.load(open(path))
    cells=d['cells']  # s, n, along(1)/across(0), rgb
    P=np.array([[c[0],c[1]] for c in cells]); al=np.array([c[2] for c in cells])
    # centres
    C=P.copy(); C[al==1,0]+=12.19/2; C[al==1,1]+=2.44/2; C[al==0,0]+=2.44/2; C[al==0,1]+=12.19/2
    # components: neighbours within one pitch along the stacking directions
    T=cKDTree(C); pairs=T.query_pairs(13.2)
    rows=[];cols=[]
    for i,j in pairs:
        ds,dn=abs(C[i,0]-C[j,0]),abs(C[i,1]-C[j,1])
        if al[i]!=al[j]: continue
        if al[i]==1 and ((ds<0.6 and dn<3.3) or (dn<0.6 and ds<13.2)): rows+=[i];cols+=[j]
        if al[i]==0 and ((dn<0.6 and ds<3.3) or (ds<0.6 and dn<13.2)): rows+=[i];cols+=[j]
    n=len(cells)
    G=coo_matrix((np.ones(len(rows)),(rows,cols)),shape=(n,n))
    nc,lab=connected_components(G,directed=False)
    size=np.bincount(lab)
    H=np.zeros(n,int)
    for i in range(n):
        if size[lab[i]]<=3: H[i]=1; continue
        base=3 if h01(key,'b',int(lab[i]))<0.55 else 4
        r=h01(key,'c',i)
        H[i]=min(5,max(2,base+(-1 if r<0.12 else (1 if r>0.88 else 0))))
    col=np.array([colour(c[3]) for c in cells])
    # runs: same orientation, same n, consecutive s at the pitch
    order=sorted(range(n),key=lambda i:(al[i],round(P[i,1],1),P[i,0]))
    runs=[]; cur=None
    for i in order:
        pitch=12.8 if al[i]==1 else 2.8
        if cur and cur['al']==al[i] and abs(cur['n']-P[i,1])<0.05 and abs(cur['s_last']+pitch-P[i,0])<0.15 and len(cur['codes'])<31:
            cur['codes'].append(col[i]*6+H[i]); cur['s_last']=P[i,0]
        else:
            cur={'al':int(al[i]),'n':P[i,1],'s0':P[i,0],'s_last':P[i,0],'codes':[col[i]*6+H[i]]}; runs.append(cur)
    s=''
    for r in runs:
        s+=enc(round((r['s0']+1000)*10),3)+enc(round((r['n']+1000)*10),3)+B64[r['al']*32+len(r['codes'])]+''.join(B64[c] for c in r['codes'])
    hist=np.bincount(H,minlength=6)[1:]
    print(key,'cells',n,'runs',len(runs),'chars',len(s),'heights 1..5',hist.tolist(),'colours',np.bincount(col,minlength=10).tolist(), file=sys.stderr)
    return {'A':d['A'],'B':d['B'],'cells':s}
if __name__=='__main__':
    out={}
    for spec in sys.argv[2:]:
        key,path=spec.split('=')
        out[key]=compile_yard(path,key)
    lines=['/**',' * Container stacks on the Port of Oakland terminal yards — GENERATED by the ports research tools',
           ' * (data/research/landmarks_ports.md): 40 ft stack footprints detected on the Esri World Imagery',
           ' * orthophoto of March 2026 (viewed only; positions, orientation and paint colour class per stack),',
           ' * in each terminal\'s wharf frame (s along the wharf line A -> B, n inland, metres).',
           ' * Heights are procedural (blocks 3-4 high, +-1; isolated boxes = single containers on chassis).',
           ' * Encoding per run of stacks: s0 (3 chars, (s+1000)*10), n (3 chars), 1 char = 32*along + count,',
           ' * then one char per stack = colour*6 + height (base64 alphabet A-Za-z0-9+/).',' */',
           'export type YardData = {A: [number, number]; B: [number, number]; cells: string};','',
           'export const YARDS: Record<string, YardData> = {']
    for k,v in out.items():
        lines.append(f"  {k}: {{A: [{v['A'][0]}, {v['A'][1]}], B: [{v['B'][0]}, {v['B'][1]}], cells:")
        c=v['cells']
        chunks=[c[i:i+110] for i in range(0,len(c),110)]
        lines.append('    '+' +\n    '.join("'"+ch+"'" for ch in chunks)+'},')
    lines.append('};')
    open(sys.argv[1],'w').write('\n'.join(lines)+'\n')
