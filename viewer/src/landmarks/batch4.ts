const ZONE_COLORS = ['#E9DDC4', '#EFE6D2', '#D9C29A', '#E3C9B0', '#CFC6B4', '#E6D3A6'];

/** Extruded Sanborn footprints, each standing on its own ground (offset from the group anchor), with a darker roof. */
function smallBuildings(b: MeshBuilder, items: [V2[], number][], anchor: V2, palette = ZONE_COLORS, seed = 0) {
  b.frame(0, 0, 0, PPIE_BRG, () => {
    items.forEach(([ring, h], i) => {
      const cx = ring.reduce((s, q) => s + q[0], 0) / ring.length;
      const cy = ring.reduce((s, q) => s + q[1], 0) / ring.length;
      const dz = groundDz(anchor, PPIE_BRG, cx, cy);
      const c = palette[Math.floor(hash01(i + seed) * palette.length)];
      b.color(c).prism(ring, dz - 1.5, dz + h, {top: false});
      b.color('#A8998A').cap(ring, dz + h);
    });
  });
}

