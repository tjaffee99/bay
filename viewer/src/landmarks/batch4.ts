/** Gabled clerestory nave from wall to wall through the dome (Sanborn "80'" eaves, Official Guide "113 feet to gables"). */
function nave(b: MeshBuilder, n: number[], w = 24, eaves = 24.4, ridge = 34.4, base = 19.8) {
  const [u0, v0, u1, v1] = n;
  const ew = Math.abs(u1 - u0) > Math.abs(v1 - v0);
  const cx = (u0 + u1) / 2;
  const cy = (v0 + v1) / 2;
  const L = ew ? Math.abs(u1 - u0) : Math.abs(v1 - v0);
  if (ew) {
    b.color(TRAV).box(cx, cy, base, L, w, eaves - base);
    b.color(NAVE_ROOF).gable(cx, cy, L, w + 0.8, eaves, ridge - eaves, false);
  } else {
    b.color(TRAV).box(cx, cy, base, w, L, eaves - base);
    b.color(NAVE_ROOF).gable(cx, cy, w + 0.8, L, eaves, ridge - eaves, true);
  }
}

/** One exhibit palace: Sanborn outline walls (65 ft), roof, cross of naves, central dome (160 ft). */
function ppiePalaceBody(b: MeshBuilder, P: {dome: V2; naves: number[][]; rings: [V2[], V2[][]][]}) {
  b.frame(0, 0, 0, PPIE_BRG, () => {
    for (const [ring, holes] of P.rings) {
      b.color(TRAV).prism(ring, 0, 18.4, {top: false, holes});
      b.color(TRAV_HI).prism(ring, 18.4, 19.8, {top: false, holes});
      b.color(ROOF).cap(ring, 19.8, holes);
    }
    for (const n of P.naves) nave(b, n);
    const [dx, dy] = P.dome;
    b.color(TRAV_SH).box(dx, dy, 19.8, 34, 34, 16.2); // crossing tower under the drum
    b.color(TRAV).cylinder(dx, dy, 16, 36, 39, 16);
    b.color(DOME_GREEN).dome(dx, dy, 15.5, 39, 9.8, 16, 4);
    b.color(TRAV_HI).cylinder(dx, dy, 2.2, 48.8, 51.5, 8);
  });
}

