// ------------------------------------------------------------------ generic helpers

function landmark(
  id: string,
  name: string,
  kind: Landmark['kind'],
  built: [number, number],
  end: number,
  anchor: V2,
  build: (b: MeshBuilder) => void,
  facts: Record<string, string>,
  sources: string[]
): Landmark {
  return {id, name, kind, built, end, anchor, build, facts, sources};
}

/**
 * Ground height at a point of a landmark's local frame (bearing `brg`) relative
 * to the anchor's ground — for groups spread over sloping ground (the Zone rises
 * ~19 m from Fillmore St to Van Ness Ave). Landmarks are built after the
 * elevation grids load (index.ts), so this matches the terrain the base uses.
 */
function groundDz(anchor: V2, brg: number, x: number, y: number) {
  const a = (brg * Math.PI) / 180;
  const p = localToLngLat(anchor, [x * Math.cos(a) + y * Math.sin(a), -x * Math.sin(a) + y * Math.cos(a)]);
  return elevationAt(p[0], p[1]) - elevationAt(anchor[0], anchor[1]);
}

/** Cheap deterministic hash → [0, 1) (colour variation of small buildings). */
function hash01(i: number) {
  const x = Math.sin(i * 127.1 + 311.7) * 43758.5453;
  return x - Math.floor(x);
}

/** Stepped tower: square stages [half-width, top z], optional cap. */
function steppedTower(b: MeshBuilder, x: number, y: number, z0: number, stages: [number, number][], color: string) {
  let z = z0;
  b.color(color);
  for (const [hw, top] of stages) {
    b.box(x, y, z, hw * 2, hw * 2, top - z);
    z = top;
  }
  return z;
}

/** Octagonal stage (prism of an 8-gon) from z0 to z1. */
function octa(b: MeshBuilder, x: number, y: number, r: number, z0: number, z1: number) {
  const ring = circle(x, y, r, 8).map(([px, py]) => {
    const a = Math.PI / 8;
    const dx = px - x;
    const dy = py - y;
    return [x + dx * Math.cos(a) - dy * Math.sin(a), y + dx * Math.sin(a) + dy * Math.cos(a)] as V2;
  });
  b.prism(ring, z0, z1);
}

